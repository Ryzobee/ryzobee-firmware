local display = require("display")
display.clear(0x0000)
display.rect(10, 20, 30, 40, 0xF800)
assert(display.read_pixel(10, 20) == 0xF800)
assert(display.read_pixel(39, 59) == 0xF800)
assert(display.read_pixel(9, 20) == 0x0000)
assert(display.read_pixel(40, 59) == 0x0000)
assert(display.read_pixel(10, 60) == 0x0000)
assert(display.show())
print("DISPLAY_RECT_PASS", "expected screen: red rectangle on black")
